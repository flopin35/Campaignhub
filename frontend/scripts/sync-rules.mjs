/**
 * Copies firebase/firestore.rules and firebase/storage.rules into frontend/api/_lib/rulesSource.js
 * so Admin → Setup can publish them in one click. Run after editing either rules file:
 *   node scripts/sync-rules.mjs
 */
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const firestore = readFileSync(join(repo, 'firebase', 'firestore.rules'), 'utf8');
const storage = readFileSync(join(repo, 'firebase', 'storage.rules'), 'utf8');
writeFileSync(
  join(here, '..', 'api', '_lib', 'rulesSource.js'),
  `// Generated by scripts/sync-rules.mjs from firebase/*.rules — do not edit by hand.\nexport const FIRESTORE_RULES = ${JSON.stringify(firestore)};\nexport const STORAGE_RULES = ${JSON.stringify(storage)};\n`,
);
console.log('rulesSource.js updated');
